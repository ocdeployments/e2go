#!/usr/bin/env node
/**
 * Builds src/lib/question-registry.generated.ts — a static key -> question-text
 * map used by the generation engine to serialize Module 3 answers as labeled
 * triples instead of bare {code: value} pairs (WS2.2 / E2 fix).
 *
 * Sources (question text lives in source files today, not a DB table):
 *   - src/data/module3/tab-*.json   ({ key, question })
 *   - src/app/apply/module3/*.tsx   (inline QUESTIONS/fields arrays: key, then question/label)
 *   - src/lib/ds160-question-sets.ts (M3-SEC-* security questions: key, label)
 *   - src/app/apply/partner2/page.tsx (P2-* questions: key, label)
 *
 * Re-run after adding/editing Module 3 questions:
 *   node scripts/generate-question-registry.mjs
 */

import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const registry = new Map();

function add(key, text) {
  if (!key || !text) return;
  const clean = text.trim();
  if (!clean) return;
  if (!registry.has(key)) registry.set(key, clean);
}

// ---------------------------------------------------------------------------
// 1. JSON tab files: [{ key, question, ... }]
// ---------------------------------------------------------------------------
const dataDir = join(ROOT, 'src/data/module3');
for (const file of readdirSync(dataDir)) {
  if (!file.endsWith('.json')) continue;
  const parsed = JSON.parse(readFileSync(join(dataDir, file), 'utf8'));
  if (Array.isArray(parsed)) {
    for (const item of parsed) {
      add(item.key, item.question ?? item.label);
    }
  } else {
    // dict shape: { "QE-01": { question, ... }, ... }
    for (const [key, item] of Object.entries(parsed)) {
      add(key, item.question ?? item.label);
    }
  }
}

// ---------------------------------------------------------------------------
// 2. Inline TSX arrays: `key: 'XXX', ... question: '...'` / `label: '...'`
//    within ~500 chars of the key (covers module3/*.tsx and partner2/page.tsx).
// ---------------------------------------------------------------------------
function extractInline(filePath) {
  const text = readFileSync(filePath, 'utf8');
  const keyRe = /key:\s*['"]([A-Z0-9-]+)['"]/g;
  let match;
  while ((match = keyRe.exec(text)) !== null) {
    const key = match[1];
    const windowText = text.slice(match.index, match.index + 600);
    const qMatch = windowText.match(/question:\s*'((?:[^'\\]|\\.)*)'/) ?? windowText.match(/question:\s*"((?:[^"\\]|\\.)*)"/);
    const lMatch = windowText.match(/label:\s*'((?:[^'\\]|\\.)*)'/) ?? windowText.match(/label:\s*"((?:[^"\\]|\\.)*)"/);
    const text2 = (qMatch ?? lMatch)?.[1];
    if (text2) add(key, text2.replace(/\\'/g, "'").replace(/\\"/g, '"'));
  }
}

const module3Dir = join(ROOT, 'src/app/apply/module3');
for (const entry of readdirSync(module3Dir, { withFileTypes: true })) {
  if (entry.isDirectory()) {
    const pagePath = join(module3Dir, entry.name, 'page.tsx');
    try { extractInline(pagePath); } catch { /* no page.tsx in this dir */ }
  }
}
extractInline(join(ROOT, 'src/app/apply/partner2/page.tsx'));

// ---------------------------------------------------------------------------
// 3. ds160-question-sets.ts: exported QuestionField[] arrays (key + label)
// ---------------------------------------------------------------------------
extractInline(join(ROOT, 'src/lib/ds160-question-sets.ts'));

// ---------------------------------------------------------------------------
// Emit
// ---------------------------------------------------------------------------
const sortedKeys = [...registry.keys()].sort();
const lines = [
  '// AUTO-GENERATED by scripts/generate-question-registry.mjs — do not edit by hand.',
  '// Re-run the script after adding or editing Module 3 questions.',
  '',
  'export const QUESTION_LABELS: Record<string, string> = {',
  ...sortedKeys.map(k => `  ${JSON.stringify(k)}: ${JSON.stringify(registry.get(k))},`),
  '};',
  '',
];

writeFileSync(join(ROOT, 'src/lib/question-registry.generated.ts'), lines.join('\n'));
console.log(`Wrote ${sortedKeys.length} question labels to src/lib/question-registry.generated.ts`);
